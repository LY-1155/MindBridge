#!/bin/bash
# =============================================================================
# Docker 入口脚本 — 启动前自动执行数据库迁移
# =============================================================================
# 失败时立即退出 (-e)、未定义变量报错 (-u)、管道中任一命令失败则失败 (-o pipefail)
set -euo pipefail

echo ">>> 执行数据库迁移..."
alembic upgrade head

echo ">>> 启动应用: $*"
exec "$@"
