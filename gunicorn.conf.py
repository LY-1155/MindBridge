"""
Gunicorn 生产配置 — uvicorn worker
=================================

将原有单进程 `uvicorn` 替换为 gunicorn 进程管理器 + 多 uvicorn worker，
提供进程守护、优雅重启、worker 回收等生产特性。

启动方式：
    gunicorn -c gunicorn.conf.py api.main:app

环境变量覆盖：
    GUNICORN_WORKERS  — worker 数量（默认 2）
"""

import multiprocessing
import os

# ---------------------------------------------------------------------------
# 绑定
# ---------------------------------------------------------------------------
bind = "0.0.0.0:8000"

# ---------------------------------------------------------------------------
# Worker
# ---------------------------------------------------------------------------
# ML 应用每个 worker 会加载独立的 torch 模型副本，内存开销大，
# 因此 worker 数不宜多；通过环境变量可调，默认 2
_cores = multiprocessing.cpu_count()
workers = int(os.environ.get("GUNICORN_WORKERS") or min(_cores, 2))
worker_class = "uvicorn.workers.UvicornWorker"

# preload_app 对 torch 不友好（fork 后 CUDA 上下文失效），保持关闭
preload_app = False

# 每个 worker 处理 1000 个请求后重启，防止 ML 模型长期运行的内存碎片
max_requests = 1000
max_requests_jitter = 200

# ---------------------------------------------------------------------------
# 超时
# ---------------------------------------------------------------------------
timeout = 120          # ML 推理可能较慢
graceful_timeout = 30  # 给正在进行的推理请求留时间
keepalive = 5

# ---------------------------------------------------------------------------
# 日志
# ---------------------------------------------------------------------------
# nginx 做接入层，gunicorn 自身不记录 access log
accesslog = "-"
# 错误日志输出到 stderr，由 Docker 日志驱动收集
errorlog = "-"
loglevel = "info"

# ---------------------------------------------------------------------------
# 进程命名（便于 ps/top 排查）
# ---------------------------------------------------------------------------
proc_name = "therapy-agent"
