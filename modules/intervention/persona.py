# ── 安全探针模板（verdict=probe 时注入，ADR-0013）──────────────
# LLM 生成的 probe_suggestion + 规则兜底。让医生在自然对话中确认"念头 vs 计划"。
# 由 generator 在构建 system_text 后追加（_get_safety_probe）。

ZHOU_SAFETY_PROBE_TEMPLATE = """

## 本轮特别任务：温和的安全确认

用户刚才的话语中有潜在风险信号（{risk_type}）。你需要在自然对话中温和地确认一次，区分"念头"与"计划"：
- 用你自己的话自然地问出，参考问题："{probe_suggestion}"
- 保持你一贯的关心、不慌乱的语气；不要审问腔，不要直接问"你是不是想自杀/自残/打人"
- 如果用户已经透露了具体计划或手段，先共情，再轻轻确认"你是不是已经有了具体的打算"
- 确认后本轮对话照常继续，不要反复追问、不要制造紧张感
"""

# ── Persona 注册表（可扩展）────────────────────────────────────

DOCTOR_PERSONAS = {
    "zhou": {
        "comfort": FAMILY_SYSTEM_PROMPT_TEMPLATE,
        "knowledge": ZHOU_KNOWLEDGE_PROMPT_TEMPLATE,
        "general": ZHOU_GENERAL_PROMPT_TEMPLATE,
    },
}


def get_doctor_prompt(route: str, persona: str = "zhou") -> str:
    """获取指定路由+persona 的 prompt 模板。

    Args:
        route: "comfort" | "knowledge" | "general"
        persona: persona 名称，默认 "zhou"

    Returns:
        未格式化的 prompt 模板字符串
    """
    personas = DOCTOR_PERSONAS.get(persona)
    if personas is None:
        raise ValueError(f"未知 persona: {persona}")
    prompt = personas.get(route)
    if prompt is None:
        raise ValueError(f"persona '{persona}' 不支持路由: {route}")
    return prompt
