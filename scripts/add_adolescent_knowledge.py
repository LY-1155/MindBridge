def _append_jsonl(path: Path, entries: list) -> tuple:
    """幂等追加：按 id 去重，返回 (新增条数, 跳过条数)。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    existing_ids = set()
    if path.exists():
        for line in path.read_text(encoding="utf-8").strip().split("\n"):
            if not line:
                continue
            try:
                existing_ids.add(json.loads(line).get("id"))
            except json.JSONDecodeError:
                pass

    added = 0
    skipped = 0
    lines = []
    for e in entries:
        if e["id"] in existing_ids:
            skipped += 1
            continue
        lines.append(json.dumps(e, ensure_ascii=False))
        existing_ids.add(e["id"])
        added += 1

    if lines:
        with path.open("a", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    return added, skipped


def main() -> int:
    targets = [
        (PUBLIC_DIR / "disorder_knowledge.jsonl", DISORDER_ENTRIES, "科普"),
        (PUBLIC_DIR / "diagnostic_frameworks.jsonl", FRAMEWORK_ENTRIES, "诊断框架"),
        (PUBLIC_DIR / "adolescent_family.jsonl", FAMILY_ENTRIES, "家庭议题"),
    ]
    total_added = 0
    for path, entries, label in targets:
        added, skipped = _append_jsonl(path, entries)
        total_added += added
        print(f"[{label}] {path.name}: 新增 {added} 条, 跳过(已存在) {skipped} 条")
    print(f"\n共新增 {total_added} 条。")
    print("下一步：python scripts/build_knowledge_index.py --backend local 重建索引")
    return 0


